#!/usr/bin/env python3
"""Generate src/unicode_data.rs from llama.cpp's src/unicode-data.cpp (same tables, same semantics).

usage: gen_unicode.py <llama.cpp>/src/unicode-data.cpp > src/unicode_data.rs
"""
import re, sys
src = open(sys.argv[1]).read()
def block(name):
    m = re.search(name + r'\s*=\s*\{(.*?)\n\};', src, re.S)
    return m.group(1)
pairs = lambda b: re.findall(r'\{0x([0-9A-Fa-f]+),\s*0x([0-9A-Fa-f]+)\}', b)
flags = pairs(block('unicode_ranges_flags'))
ws = re.findall(r'0x([0-9A-Fa-f]+)', block('unicode_set_whitespace'))
lower = pairs(block('unicode_map_lowercase'))
o = ['// @generated by tools/gen_unicode.py from llama.cpp src/unicode-data.cpp. Do not edit.',
     '// (start codepoint, flags); a range ends where the next one starts.']
o.append('pub static RANGES_FLAGS: [(u32, u16); %d] = [' % len(flags))
o += ['(0x%s, 0x%s),' % p for p in flags]
o.append('];')
o.append('pub static WHITESPACE: [u32; %d] = [' % len(ws))
o += ['0x%s,' % w for w in sorted(ws, key=lambda x: int(x, 16))]
o.append('];')
o.append('/// (upper, lower), sorted by the first element.')
o.append('pub static MAP_LOWERCASE: [(u32, u32); %d] = [' % len(lower))
o += ['(0x%s, 0x%s),' % p for p in lower]
o.append('];')
print('\n'.join(o))
